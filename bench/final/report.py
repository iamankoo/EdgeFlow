#!/usr/bin/env python3
"""Turns the raw files of bench/final/run.sh into bench/results/<label>/report.md (measured numbers only).

    python3 bench/final/report.py <label>
"""
import csv
import os
import re
import statistics
import sys

STRATEGIES = ["round_robin", "weighted", "least_connections", "consistent_hashing"]


def read(path):
    try:
        return open(path, encoding="utf-8").read()
    except OSError:
        return ""


def wrk(path):
    t = read(path)
    d = {}
    m = re.search(r"Requests/sec:\s+([\d.]+)", t)
    d["rps"] = float(m.group(1)) if m else 0.0
    for p in ("50", "75", "90", "95", "99", "99.9"):
        m = re.search(rf"^p{re.escape(p)} (\d+)$", t, re.M)
        d["p" + p] = int(m.group(1)) / 1000.0 if m else float("nan")
    m = re.search(r"^requests (\d+)$", t, re.M)
    d["requests"] = int(m.group(1)) if m else 0
    m = re.search(r"^duration_us (\d+)$", t, re.M)
    d["seconds"] = int(m.group(1)) / 1e6 if m else 0.0
    m = re.search(r"errors connect=(\d+) read=(\d+) write=(\d+) status=(\d+) timeout=(\d+)", t)
    d["errors"] = dict(zip(("connect", "read", "write", "status", "timeout"), map(int, m.groups()))) if m else {}
    return d


def counts(path):
    out = {}
    for line in read(path).splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[1].isdigit():
            out[parts[0]] = int(parts[1])
    return out


def pidstat(path):
    """Average CPU % (of one core) and the last RSS (MB) of the gateway from `pidstat -u -r`."""
    cpu, rss = [], []
    # pidstat prints a CPU table and a memory table; take the columns by header
    mode = None
    for line in read(path).splitlines():
        if "%CPU" in line and "Command" in line:
            mode = "cpu"
            continue
        if "RSS" in line and "Command" in line:
            mode = "mem"
            continue
        f = line.split()
        if not f or line.startswith("Average") or line.startswith("Linux"):
            continue
        try:
            if mode == "cpu":
                cpu.append(float(f[-3]))
            elif mode == "mem":
                rss.append(float(f[-3]) / 1024.0)
        except ValueError:
            pass
    return (statistics.mean(cpu) if cpu else float("nan"), max(rss) if rss else float("nan"))


def fmt(x, nd=2):
    return "n/a" if x != x else f"{x:.{nd}f}"


def main():
    label = sys.argv[1]
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results", label)
    L = []
    w = L.append
    env = read(os.path.join(d, "environment.txt"))
    w(f"# Final benchmark report: {label}\n")
    w("Generated by `bench/final/report.py` from the raw files in this directory. Every number was measured by `bench/final/run.sh`.\n")
    w("```\n" + env.strip() + "\n```\n")

    w("## 1. Routing strategies under load (10 backends)\n")
    w("Gateway: PostgreSQL registry, health checks, reliability layer, Redis cache and rate limiter, metrics, all ON; every request is "
      "`GET /proxy/bench/` with `Cache-Control: no-cache` (it reaches a backend). Strategies other than least_connections run with "
      "`proxy.connection_counting: auto` and `routing.snapshot_ttl_ms: 250`; least_connections needs live connection counts, so it "
      "writes them to PostgreSQL and keeps no snapshot.\n")
    w("| strategy | requests | seconds | req/s | p50 ms | p90 ms | p95 ms | p99 ms | non-2xx | socket errors | gateway CPU (cores) | gateway RSS MB |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    dist = {}
    for s in STRATEGIES:
        r = wrk(os.path.join(d, f"strat-{s}.wrk.txt"))
        cpu, rss = pidstat(os.path.join(d, f"strat-{s}.pidstat.txt"))
        e = r["errors"]
        sock = sum(e.get(k, 0) for k in ("connect", "read", "write", "timeout"))
        w(f"| {s} | {r['requests']:,} | {r['seconds']:.1f} | {r['rps']:.0f} | {fmt(r['p50'])} | {fmt(r['p90'])} | {fmt(r['p95'])} | "
          f"{fmt(r['p99'])} | {e.get('status', 0)} | {sock} | {fmt(cpu / 100.0)} | {fmt(rss, 1)} |")
        before = counts(os.path.join(d, f"strat-{s}.before.txt"))
        after = counts(os.path.join(d, f"strat-{s}.after.txt"))
        dist[s] = {k: after.get(k, 0) - before.get(k, 0) for k in after}
    w("")
    w("### Requests each backend served (backend `/metrics`, delta over the measured run; includes about one health probe per 2 s per backend)\n")
    ids = sorted({k for v in dist.values() for k in v}, key=lambda s: int(s[1:]))
    w("| backend | " + " | ".join(STRATEGIES) + " |")
    w("|---|" + "---|" * len(STRATEGIES))
    for b in ids:
        row = []
        for s in STRATEGIES:
            tot = sum(dist[s].values()) or 1
            v = dist[s].get(b, 0)
            row.append(f"{v:,} ({100.0 * v / tot:.1f}%)")
        w(f"| {b} | " + " | ".join(row) + " |")
    w("| total | " + " | ".join(f"{sum(dist[s].values()):,}" for s in STRATEGIES) + " |")
    w("")
    if "weighted" in dist and dist["weighted"]:
        weights = {f"b{i + 1}": x for i, x in enumerate([1, 1, 1, 1, 1, 2, 2, 2, 3, 3])}
        tw = sum(weights.values())
        tot = sum(dist["weighted"].values()) or 1
        dev = max(abs(100.0 * dist["weighted"].get(b, 0) / tot - 100.0 * wt / tw) for b, wt in weights.items())
        w(f"Weighted routing used the weights 1,1,1,1,1,2,2,2,3,3 (b1..b10): the largest deviation of any backend's share from its "
          f"weight's share is {dev:.2f} percentage points.\n")
    keys = counts(os.path.join(d, "keys-consistent_hashing.txt"))
    if keys:
        tot = sum(keys.values())
        w("Consistent hashing is keyed by the client address, so the load generator (one address) is sticky to one backend by design; "
          f"the spread of the ring was measured with {tot:,} routing decisions for distinct keys (`GET /services/bench/route?key=...`):\n")
        w("| backend | keys | share |")
        w("|---|---|---|")
        for b in sorted(keys, key=lambda s: int(s[1:])):
            w(f"| {b} | {keys[b]:,} | {100.0 * keys[b] / tot:.1f}% |")
        w("")

    w("## 2. Dynamic membership and failure injection (10 backends, round_robin, 64 connections)\n")
    w("The same scenario against a fresh gateway process, once with the benchmark's `proxy.upstream_timeout_ms: 10000` (connect timeout 2000) and once with "
      "`1000` (connect timeout 500), because the timeout decides how long a request to a hung backend ties up its client connection.\n")
    summary_rows = []
    for name, timeout in (("10s", 10000), ("1s", 1000)):
        pre = os.path.join(d, f"dyn-{name}")
        if not read(pre + ".wrk.txt"):
            continue
        w(f"### 2.{len(summary_rows) + 1} upstream timeout {timeout} ms\n")
        ev = read(pre + ".events.txt").strip()
        w("Events (seconds since the load started):\n\n```\n" + ev + "\n```\n")
        r = wrk(pre + ".wrk.txt")
        e = r["errors"]
        sock = sum(e.get(k, 0) for k in ("connect", "read", "write", "timeout"))
        answered = r["requests"]
        avail = 100.0 * (answered - e.get("status", 0)) / answered if answered else float("nan")
        cpu, rss = pidstat(pre + ".pidstat.txt")
        w("| requests | seconds | req/s | p50 ms | p90 ms | p95 ms | p99 ms | p99.9 ms | non-2xx answers | no answer (socket errors / timeouts) | availability (2xx / answered) |")
        w("|---|---|---|---|---|---|---|---|---|---|---|")
        w(f"| {r['requests']:,} | {r['seconds']:.1f} | {r['rps']:.0f} | {fmt(r['p50'])} | {fmt(r['p90'])} | {fmt(r['p95'])} | {fmt(r['p99'])} | "
          f"{fmt(r['p99.9'])} | {e.get('status', 0):,} | {sock:,} | {avail:.3f}% |")
        w("")
        w(f"Gateway process: {fmt(cpu / 100.0)} cores on average, peak RSS {fmt(rss, 1)} MB.\n")
        summary_rows.append((timeout, r, e, sock, avail))
        try:
            rows = list(csv.DictReader(open(pre + ".timeline.csv")))
        except OSError:
            rows = []

        def num(row, key):
            try:
                return int(row[key])
            except (ValueError, TypeError):
                return 0
        if rows:
            w("Timeline (every 2 s; 2xx/5xx are answers per second to clients, the others are cumulative counters of the gateway):\n")
            w("| t (s) | routable instances | 2xx per s | 5xx per s | retries (total) | failovers (total) | circuit trips (total) | circuit rejections (total) |")
            w("|---|---|---|---|---|---|---|---|")
            prev = None
            for row in rows:
                if prev is not None and int(row["t"]) % 2 == 0:
                    w(f"| {row['t']} | {row['routable']} | {(num(row, 'resp_2xx') - num(prev, 'resp_2xx')) // max(1, int(row['t']) - int(prev['t']))} | "
                      f"{(num(row, 'resp_5xx') - num(prev, 'resp_5xx')) // max(1, int(row['t']) - int(prev['t']))} | {num(row, 'retries')} | "
                      f"{num(row, 'failovers')} | {num(row, 'circuit_trips')} | {num(row, 'circuit_rejections')} |")
                prev = row
            w("")
        m = read(pre + ".metrics.txt")
        keep = [l for l in m.splitlines() if re.match(r"edgeflow_(retries_total|failovers_total|retry_exhausted_total|circuit_breaker_trips_total|circuit_breaker_rejections_total|backend_attempts_total|proxy_gateway_errors_total|http_responses_total)", l)]
        w("Gateway counters at the end of the run:\n\n```\n" + "\n".join(keep) + "\n```\n")
        fin = read(pre + ".final-instances.txt").strip()
        w("Registry at the end of the run:\n\n```\n" + fin + "\n```\n")
        t = read(pre + ".docker-stats-mid.txt").strip()
        if t:
            w("Containers during the failure phase (`docker stats`, one sample):\n\n```\n" + t + "\n```\n")
    if summary_rows:
        w("### Summary of the two runs\n")
        w("| upstream timeout | requests | req/s | p50 ms | p95 ms | p99 ms | non-2xx | no answer | availability |")
        w("|---|---|---|---|---|---|---|---|---|")
        for timeout, r, e, sock, avail in summary_rows:
            w(f"| {timeout} ms | {r['requests']:,} | {r['rps']:.0f} | {fmt(r['p50'])} | {fmt(r['p95'])} | {fmt(r['p99'])} | {e.get('status', 0):,} | {sock:,} | {avail:.3f}% |")
        w("")
    open(os.path.join(d, "report.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(os.path.join(d, "report.md"))


if __name__ == "__main__":
    main()
